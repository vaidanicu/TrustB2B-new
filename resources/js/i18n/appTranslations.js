/**
 * The account's own saved preference (auth.user.locale, persisted via
 * LocaleController) — distinct from the marketing page's per-URL locale,
 * which has no account to read from. Falls back to 'ro' before login.
 */
export function useAppTranslations() {
    const { auth } = usePage().props;
    const locale = APP_LOCALES.includes(auth?.user?.locale) ? auth.user.locale : 'ro';

    return { t: APP_TRANSLATIONS[locale], locale };
}

